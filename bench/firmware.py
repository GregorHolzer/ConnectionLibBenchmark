"""Turning a `Config` into a flashed board.

The firmware is configured at build time: this module writes include/bench_config.h, which
src/Config.hpp includes, and PlatformIO rebuilds only the files that depend on it. `project` is
the firmware directory, so the same code flashes ConnectionLibBenchmarkRaw.
"""

import json
import re
import subprocess
from pathlib import Path

from . import configs

REPO_ROOT = Path(__file__).resolve().parent.parent
BOARDS_FILE = REPO_ROOT / "boards.json"
TECH_ENUM = {"none": "None", "espnow": "EspNow", "lora": "LoRa", "zigbee": "Zigbee"}


class FirmwareError(RuntimeError):
    pass


def load_boards():
    """The two boards' addresses and ports, as `bench.py prepare` recorded them."""
    if not BOARDS_FILE.exists():
        raise FirmwareError(f"{BOARDS_FILE.name} not found - run `bench.py prepare` first")
    return json.loads(BOARDS_FILE.read_text())


def _mac_initialiser(mac):
    octets = mac.split(":")
    if len(octets) != 6:
        raise FirmwareError(f"not a MAC address: {mac!r}")
    return "{" + ", ".join(f"0x{int(o, 16):02X}" for o in octets) + "}"


def render_header(config, peer_mac, gateway_xbee64, run_id):
    """The text of bench_config.h for one configuration. Every macro src/Config.hpp reads."""
    lora = dict(configs.LORA_BASELINE, **config.params) if config.tech == "lora" \
        else configs.LORA_BASELINE
    values = {
        "BENCH_TECH": TECH_ENUM[config.tech],
        "BENCH_RUN_ID": run_id & 0xFF,
        "BENCH_PAYLOAD": config.payload,
        "BENCH_EXCHANGES": config.exchanges,
        "BENCH_IDLE_MS": config.idle_ms,
        "BENCH_ACK_WAIT_MS": configs.ack_wait_ms(config),
        "BENCH_LEASE_S": configs.lease_seconds(config),
        "BENCH_LORA_BW_KHZ": lora["bw"],
        "BENCH_LORA_SF": lora["sf"],
        "BENCH_LORA_CR": lora["cr"],
        "BENCH_LORA_PWR": lora["pwr"],
        "BENCH_LORA_PREAMBLE": lora["preamble"],
        "BENCH_ESPNOW_CHANNEL": config.params.get("channel", configs.ESPNOW_BASELINE["channel"]),
        "BENCH_PEER_MAC": _mac_initialiser(peer_mac),
        "BENCH_PEER_XBEE": f"0x{int(str(gateway_xbee64), 16):016X}ULL",
    }
    lines = [f"// Generated by bench/firmware.py for {config.key}. Do not edit.", "#pragma once"]
    lines += [f"#define {name} {value}" for name, value in values.items()]
    return "\n".join(lines) + "\n"


def flash(project, env, port, header_text, pio="pio"):
    """Write the header, build `env` and upload it. Raises FirmwareError with the build's tail."""
    header = Path(project) / "include" / "bench_config.h"
    header.parent.mkdir(exist_ok=True)
    header.write_text(header_text)
    result = subprocess.run([pio, "run", "-d", str(project), "-e", env, "-t", "upload",
                             "--upload-port", port], capture_output=True, text=True)
    if result.returncode != 0:
        tail = "\n".join((result.stdout + result.stderr).splitlines()[-25:])
        raise FirmwareError(f"building or uploading {env} failed:\n{tail}")


def read_mac(port, pio="pio"):
    """The board's WiFi MAC, which is its ESP-NOW address."""
    result = subprocess.run([pio, "pkg", "exec", "--", "esptool.py", "--port", port, "read_mac"],
                            capture_output=True, text=True, cwd=REPO_ROOT)
    macs = re.findall(r"MAC: ([0-9A-Fa-f:]{17})", result.stdout)
    if not macs:
        raise FirmwareError(f"esptool reported no MAC for {port}:\n{result.stdout[-400:]}")
    return macs[-1]

